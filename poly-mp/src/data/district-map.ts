export function getDistrictMap(province: string | null, city: string | null): CityDistrictMap | null {
  if (!province || !city) return null;
  return MAPS[`${province}|${city}`] ?? null;
}

/**
 * 국회 선거구 표기 정규화 → 접미사("갑"/"을"/"병"/"정"/"무").
 * 앱의 국회의원 region.district는 접미사 한 글자이고("고양시정"→"정"),
 * 매핑 테이블 값은 가독성을 위해 전체명("고양시정")일 수도 있어 양쪽 다 처리.
 */
function assemblySuffix(name: string): string {
  const m = name.match(/([갑을병정무])$/);
  return m ? m[1] : name;
}

/** 지방의원이 선택한 국회 선거구(assembly)에 속하는지. 매핑 정보가 없으면 null(판단 불가). */
export function belongsToAssembly(
  map: CityDistrictMap | null,
  level: 'provincial' | 'city',
  councilDistrict: string,
  assemblyDistrict: string,
): boolean | null {
  if (!map) return null;
  const table = level === 'provincial' ? map.provincial : map.city;
  const mapped = table[councilDistrict];
  if (!mapped) return null; // 비례대표 등 매핑 밖 — 판단 불가
  return assemblySuffix(mapped) === assemblySuffix(assemblyDistrict);
}
